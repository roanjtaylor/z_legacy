package com.craft.save;

import com.craft.entity.Player;
import com.craft.game.GameMode;
import com.craft.game.Inventory;
import com.craft.game.Survival;
import com.craft.render.Camera;
import com.craft.world.BlockType;
import com.craft.world.Blocks;
import com.craft.world.Chunk;
import com.craft.world.Sky;
import com.craft.world.World;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.zip.GZIPInputStream;
import java.util.zip.GZIPOutputStream;

/**
 * Reads and writes worlds under {@code saves/}, in this project directory. No database, no
 * server: a world is one readable {@code level.json} plus a folder of compressed chunks.
 *
 * <p>Only chunks the player actually edited are written. Terrain is a pure function of the
 * seed, so an untouched chunk can be regenerated byte for byte and storing it would be dead
 * weight — a world you have explored for an hour but not built in is a single small file.
 */
public class WorldStore {

    private static final Path SAVES_ROOT = Path.of("saves");
    private static final int FORMAT_VERSION = 1;

    /** Marks a chunk file as ours and lets a future format change be detected rather than crash. */
    private static final int CHUNK_MAGIC = 0x43524654;

    private final Path directory;
    private final String name;

    public WorldStore(String name) {
        this.name = name;
        this.directory = SAVES_ROOT.resolve(sanitise(name));
    }

    /** Keeps a typed world name from escaping the saves folder or upsetting the filesystem. */
    private static String sanitise(String name) {
        String cleaned = name.trim().replaceAll("[^A-Za-z0-9 _-]", "_");
        if (cleaned.isEmpty()) {
            cleaned = "world";
        }
        return cleaned.length() > 48 ? cleaned.substring(0, 48) : cleaned;
    }

    public String getName() {
        return name;
    }

    public Path getDirectory() {
        return directory;
    }

    public boolean exists() {
        return Files.isRegularFile(directory.resolve("level.json"));
    }

    // -------------------------------------------------------------------- world listing

    /** Everything under {@code saves/}, most recently played first. */
    public static List<Summary> list() {
        List<Summary> worlds = new ArrayList<>();
        if (!Files.isDirectory(SAVES_ROOT)) {
            return worlds;
        }
        try (DirectoryStream<Path> stream = Files.newDirectoryStream(SAVES_ROOT)) {
            for (Path entry : stream) {
                Path level = entry.resolve("level.json");
                if (!Files.isRegularFile(level)) {
                    continue;
                }
                try {
                    Map<String, Object> root = Json.parseObject(Files.readString(level));
                    worlds.add(new Summary(
                            Json.string(root, "name", entry.getFileName().toString()),
                            entry.getFileName().toString(),
                            Json.longValue(root, "seed", 0),
                            GameMode.byName(Json.string(root, "mode", "survival")),
                            Json.longValue(root, "lastPlayed", 0)));
                } catch (Exception e) {
                    System.err.println("Skipping unreadable world " + entry + ": " + e.getMessage());
                }
            }
        } catch (IOException e) {
            System.err.println("Could not list saves: " + e.getMessage());
        }
        worlds.sort(Comparator.comparingLong((Summary s) -> s.lastPlayed).reversed());
        return worlds;
    }

    public static class Summary {
        public final String name;
        public final String folder;
        public final long seed;
        public final GameMode mode;
        public final long lastPlayed;

        Summary(String name, String folder, long seed, GameMode mode, long lastPlayed) {
            this.name = name;
            this.folder = folder;
            this.seed = seed;
            this.mode = mode;
            this.lastPlayed = lastPlayed;
        }
    }

    public static boolean delete(String folder) {
        Path target = SAVES_ROOT.resolve(sanitise(folder));
        if (!Files.isDirectory(target)) {
            return false;
        }
        try (java.util.stream.Stream<Path> paths = Files.walk(target)) {
            paths.sorted(Comparator.reverseOrder()).forEach(path -> {
                try {
                    Files.delete(path);
                } catch (IOException e) {
                    System.err.println("Could not delete " + path + ": " + e.getMessage());
                }
            });
            return true;
        } catch (IOException e) {
            System.err.println("Could not delete world: " + e.getMessage());
            return false;
        }
    }

    // ---------------------------------------------------------------------- level state

    /** Everything about a world that is not a block. */
    public static class LevelState {
        public String name = "World";
        public long seed;
        public GameMode mode = GameMode.SURVIVAL;
        public float timeOfDay = 0.2f;
        public float playerX;
        public float playerY = 70;
        public float playerZ;
        public float yaw = -45;
        public float pitch = -8;
        public boolean flying;
        public int health = Survival.MAX_HEALTH;
        public int renderDistance = 8;
        public final Inventory inventory = new Inventory();
    }

    public void saveLevel(LevelState state) {
        try {
            Files.createDirectories(directory);

            Json.Writer root = new Json.Writer()
                    .put("format", FORMAT_VERSION)
                    .put("name", state.name)
                    .put("seed", state.seed)
                    .put("mode", state.mode.name().toLowerCase())
                    .put("timeOfDay", state.timeOfDay)
                    .put("renderDistance", state.renderDistance)
                    .put("lastPlayed", System.currentTimeMillis());

            Json.Writer player = new Json.Writer()
                    .put("x", state.playerX)
                    .put("y", state.playerY)
                    .put("z", state.playerZ)
                    .put("yaw", state.yaw)
                    .put("pitch", state.pitch)
                    .put("flying", state.flying)
                    .put("health", state.health);
            root.put("player", player);

            List<Object> slots = new ArrayList<>();
            for (int i = 0; i < state.inventory.size(); i++) {
                Inventory.Slot slot = state.inventory.slot(i);
                if (slot.isEmpty()) {
                    continue;
                }
                slots.add(new Json.Writer()
                        .put("slot", i)
                        .put("block", slot.type.name)
                        .put("count", slot.count));
            }
            root.put("selected", state.inventory.getSelected());
            root.put("inventory", slots);

            // Write beside the real file and move into place, so a crash mid-save cannot
            // leave a half-written level.json behind.
            Path target = directory.resolve("level.json");
            Path temp = directory.resolve("level.json.tmp");
            Files.writeString(temp, root + "\n", StandardCharsets.UTF_8);
            Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING);
        } catch (IOException e) {
            System.err.println("Failed to save level: " + e.getMessage());
        }
    }

    public LevelState loadLevel() {
        LevelState state = new LevelState();
        state.name = name;
        try {
            Map<String, Object> root = Json.parseObject(
                    Files.readString(directory.resolve("level.json")));

            state.name = Json.string(root, "name", name);
            state.seed = Json.longValue(root, "seed", 0);
            state.mode = GameMode.byName(Json.string(root, "mode", "survival"));
            state.timeOfDay = Json.floatValue(root, "timeOfDay", 0.2f);
            state.renderDistance = Json.integer(root, "renderDistance", 8);

            Map<String, Object> player = Json.object(root, "player");
            state.playerX = Json.floatValue(player, "x", 0);
            state.playerY = Json.floatValue(player, "y", 70);
            state.playerZ = Json.floatValue(player, "z", 0);
            state.yaw = Json.floatValue(player, "yaw", -45);
            state.pitch = Json.floatValue(player, "pitch", -8);
            state.flying = Json.bool(player, "flying", false);
            state.health = Json.integer(player, "health", Survival.MAX_HEALTH);

            for (Object entry : Json.array(root, "inventory")) {
                if (!(entry instanceof Map)) {
                    continue;
                }
                @SuppressWarnings("unchecked")
                Map<String, Object> slot = (Map<String, Object>) entry;
                BlockType type = Blocks.byName(Json.string(slot, "block", ""));
                int index = Json.integer(slot, "slot", -1);
                if (type != null && index >= 0 && index < state.inventory.size()) {
                    state.inventory.setSlot(index, type, Json.integer(slot, "count", 1));
                }
            }
            state.inventory.setSelected(Json.integer(root, "selected", 0));
        } catch (Exception e) {
            System.err.println("Failed to load level.json: " + e.getMessage());
        }
        return state;
    }

    // ---------------------------------------------------------------------------- chunks

    private Path chunkPath(int chunkX, int chunkZ) {
        return directory.resolve("chunks").resolve("c." + chunkX + "." + chunkZ + ".dat");
    }

    /** Writes a chunk, but only if the player has changed it. */
    public void saveChunk(Chunk chunk) {
        if (!chunk.isModified()) {
            return;
        }
        try {
            Path path = chunkPath(chunk.chunkX, chunk.chunkZ);
            Files.createDirectories(path.getParent());

            try (OutputStream out = Files.newOutputStream(path);
                 GZIPOutputStream gzip = new GZIPOutputStream(out)) {
                writeInt(gzip, CHUNK_MAGIC);
                writeInt(gzip, FORMAT_VERSION);
                writeInt(gzip, chunk.chunkX);
                writeInt(gzip, chunk.chunkZ);
                gzip.write(chunk.blockArray());
            }
        } catch (IOException e) {
            System.err.println("Failed to save chunk " + chunk.chunkX + ","
                    + chunk.chunkZ + ": " + e.getMessage());
        }
    }

    /** @return the saved chunk, or null if this one was never edited and should be regenerated */
    public Chunk loadChunk(int chunkX, int chunkZ) {
        Path path = chunkPath(chunkX, chunkZ);
        if (!Files.isRegularFile(path)) {
            return null;
        }
        try (InputStream in = Files.newInputStream(path);
             GZIPInputStream gzip = new GZIPInputStream(in)) {

            if (readInt(gzip) != CHUNK_MAGIC) {
                System.err.println("Ignoring " + path + ": not a Craft chunk");
                return null;
            }
            int version = readInt(gzip);
            if (version != FORMAT_VERSION) {
                System.err.println("Ignoring " + path + ": format " + version
                        + ", expected " + FORMAT_VERSION);
                return null;
            }
            readInt(gzip);
            readInt(gzip);

            byte[] blocks = readFully(gzip, Chunk.BLOCK_COUNT);
            if (blocks == null) {
                System.err.println("Ignoring truncated chunk " + path);
                return null;
            }

            Chunk chunk = new Chunk(chunkX, chunkZ);
            System.arraycopy(blocks, 0, chunk.blockArray(), 0, Chunk.BLOCK_COUNT);
            chunk.rebuildHeightmap();
            // It came from disk because it was edited; keep that true so it saves again.
            chunk.setModified(true);
            return chunk;
        } catch (IOException e) {
            System.err.println("Failed to load chunk " + chunkX + "," + chunkZ
                    + ": " + e.getMessage());
            return null;
        }
    }

    /** Saves every loaded chunk that has been edited. */
    public int saveAllChunks(World world) {
        int saved = 0;
        for (Chunk chunk : world.loadedChunks()) {
            if (chunk.isModified()) {
                saveChunk(chunk);
                saved++;
            }
        }
        return saved;
    }

    /** Gathers the current game state into something that can be written. */
    public static LevelState capture(String name, World world, Sky sky, Player player,
                                     Camera camera, GameMode mode, Inventory inventory,
                                     Survival survival) {
        LevelState state = new LevelState();
        state.name = name;
        state.seed = world.getSeed();
        state.mode = mode;
        state.timeOfDay = sky.getTimeOfDay();
        state.renderDistance = world.getRenderDistance();
        state.playerX = player.position.x;
        state.playerY = player.position.y;
        state.playerZ = player.position.z;
        state.yaw = camera.getYaw();
        state.pitch = camera.getPitch();
        state.flying = player.isFlying();
        state.health = survival.getHealth();

        for (int i = 0; i < inventory.size(); i++) {
            Inventory.Slot slot = inventory.slot(i);
            if (!slot.isEmpty()) {
                state.inventory.setSlot(i, slot.type, slot.count);
            }
        }
        state.inventory.setSelected(inventory.getSelected());
        return state;
    }

    // --------------------------------------------------------------------------- binary

    private static void writeInt(OutputStream out, int value) throws IOException {
        out.write((value >>> 24) & 0xFF);
        out.write((value >>> 16) & 0xFF);
        out.write((value >>> 8) & 0xFF);
        out.write(value & 0xFF);
    }

    private static int readInt(InputStream in) throws IOException {
        int a = in.read();
        int b = in.read();
        int c = in.read();
        int d = in.read();
        if ((a | b | c | d) < 0) {
            throw new IOException("Unexpected end of chunk file");
        }
        return (a << 24) | (b << 16) | (c << 8) | d;
    }

    /** GZIP streams deliver in chunks, so a single read() can come back short. */
    private static byte[] readFully(InputStream in, int expected) throws IOException {
        ByteArrayOutputStream buffer = new ByteArrayOutputStream(expected);
        byte[] scratch = new byte[8192];
        int read;
        while ((read = in.read(scratch)) > 0) {
            buffer.write(scratch, 0, read);
        }
        byte[] result = buffer.toByteArray();
        return result.length == expected ? result : null;
    }

    /** Ensures the saves folder exists and returns a name not already in use. */
    public static String uniqueName(String requested) {
        String base = sanitise(requested);
        String candidate = base;
        int suffix = 1;
        while (Files.isDirectory(SAVES_ROOT.resolve(candidate))) {
            candidate = base + " (" + (++suffix) + ")";
        }
        return candidate;
    }
}
